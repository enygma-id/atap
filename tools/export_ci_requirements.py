"""Regenerate hash-verified CI graphs from the existing engine lock and QA pins."""
import argparse
from pathlib import Path
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--uv", default="uv")
    parser.add_argument(
        "--check-exports", action="store_true",
        help="Check CI/runtime exports against uv.lock without modifying files.",
    )
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    def run(*parts):
        subprocess.run([args.uv, *map(str, parts)], cwd=root, check=True)
    header = "# SPDX-License-Identifier: AGPL-3.0-only\n# Generated by tools/export_ci_requirements.py; review updates and rerun goldens.\n"
    with tempfile.TemporaryDirectory(prefix="atap-requirements-") as temporary:
        tmp = Path(temporary)
        stale = []
        for name, extras in [("ci", ["--extra", "dev", "--extra", "server"]), ("runtime", ["--extra", "server"])]:
            target = root / "requirements" / (name + ".txt")
            generated = tmp / (name + ".txt")
            run("export", "--locked", "--no-dev", "--no-emit-project", *extras, "-o", generated)
            content = header + "\n".join(line for line in generated.read_text(encoding="utf-8").splitlines() if not line.startswith("#")) + "\n"
            if args.check_exports:
                if not target.exists() or target.read_text(encoding="utf-8") != content:
                    stale.append(str(target.relative_to(root)))
            else:
                target.write_text(content, encoding="utf-8", newline="\n")
        if args.check_exports:
            if stale:
                parser.exit(1, "Stale lock exports: " + ", ".join(stale) + ". Run python tools/export_ci_requirements.py.\n")
            print("CI/runtime exports match uv.lock.")
            return
        raw = tmp / "raw.txt"
        run("export", "--locked", "--no-dev", "--no-emit-project", "--no-hashes", "--extra", "dev", "--extra", "server", "-o", raw)
        constraints = tmp / "constraints.txt"
        constraints.write_text("\n".join(line for line in raw.read_text().splitlines() if not line.startswith(("numpy==", "scipy==", "rasterio=="))) + "\n", encoding="utf-8")
        common = ["--generate-hashes", "--no-header", "--no-annotate"]
        run("pip", "compile", "pyproject.toml", "--extra", "dev", "--extra", "server", "--constraint", constraints, "--constraint", "requirements/numpy1.in", "--python-version", "3.12", *common, "-o", "requirements/numpy1.txt")
        run("pip", "compile", "requirements/build.in", "--constraint", constraints, "--universal", "--python-version", "3.10", *common, "-o", "requirements/build.txt")
        run("pip", "compile", "requirements/cff.in", "--universal", "--python-version", "3.10", *common, "-o", "requirements/cff.txt")
        for name in ("numpy1", "build", "cff"):
            target = root / "requirements" / (name + ".txt")
            target.write_text(header + target.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
